import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SYNAPSE_IMAGE = "matrixdotorg/synapse:v1.157.0";
const POSTGRES_IMAGE = "postgres:16.9-bookworm";
const SYNAPSE_LOOPBACK_PORT = "127.0.0.1:${SYNARA_PORT:-8008}:8008";

const indentation = (line) => line.length - line.trimStart().length;

function parseComposeServices(compose) {
  const services = new Map();
  let inServices = false;
  let currentService;

  for (const line of compose.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const indent = indentation(line);
    if (indent === 0) {
      if (trimmed === "services:") {
        inServices = true;
        currentService = undefined;
        continue;
      }
      if (inServices) break;
      continue;
    }
    if (!inServices) continue;

    const serviceMatch =
      indent === 2 ? trimmed.match(/^([A-Za-z0-9_.-]+):$/) : null;
    if (serviceMatch) {
      currentService = [];
      services.set(serviceMatch[1], currentService);
      continue;
    }
    currentService?.push(line);
  }

  return services;
}

function getServicePropertyBlock(lines, property) {
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (indentation(line) !== 4) continue;
    const match = line.trim().match(/^([A-Za-z0-9_.-]+):(?:\s*(.*))?$/);
    if (!match || match[1] !== property) continue;

    const children = [];
    for (
      let childIndex = index + 1;
      childIndex < lines.length;
      childIndex += 1
    ) {
      const child = lines[childIndex];
      if (child.trim() && indentation(child) <= 4) break;
      children.push(child);
    }
    return { inline: match[2] ?? "", children };
  }
  return undefined;
}

function getServiceScalar(lines, property) {
  return getServicePropertyBlock(lines, property)?.inline.replace(
    /^['"]|['"]$/g,
    ""
  );
}

function getServicePorts(lines) {
  const block = getServicePropertyBlock(lines, "ports");
  if (!block) return [];
  if (block.inline && block.inline !== "[]")
    return [`<inline:${block.inline}>`];

  const ports = [];
  for (const line of block.children) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const entry =
      indentation(line) === 6 ? trimmed.match(/^-\s+(.+)$/)?.[1] : undefined;
    if (entry) {
      ports.push(entry.replace(/^['"]|['"]$/g, ""));
    } else if (ports.length === 0) {
      ports.push(`<malformed:${trimmed}>`);
    }
  }
  return ports;
}

function getCommandCase(launcher, command) {
  const escaped = command.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return launcher.match(
    new RegExp(`\\n\\s*${escaped}\\)\\n([\\s\\S]*?)\\n\\s*;;`)
  )?.[1];
}

export function inspectSynapseHarness({ compose, template, launcher, ignore }) {
  const errors = [];
  const requireText = (value, expected, message) => {
    if (!value.includes(expected)) errors.push(message);
  };

  const services = parseComposeServices(compose);
  const synapse = services.get("synapse");
  const postgres = services.get("postgres");
  if (!synapse || getServiceScalar(synapse, "image") !== SYNAPSE_IMAGE) {
    errors.push("Synapse integration image must remain pinned to v1.157.0.");
  }
  if (!postgres || getServiceScalar(postgres, "image") !== POSTGRES_IMAGE) {
    errors.push(
      "PostgreSQL integration image must remain pinned to 16.9-bookworm."
    );
  }

  const synapsePorts = synapse ? getServicePorts(synapse) : [];
  if (synapsePorts.length !== 1 || synapsePorts[0] !== SYNAPSE_LOOPBACK_PORT) {
    errors.push(
      "Disposable Synapse must expose exactly one loopback-only 8008 mapping."
    );
  }
  if (postgres && getServicePorts(postgres).length > 0) {
    errors.push("Disposable PostgreSQL must not publish host ports.");
  }
  requireText(
    compose,
    "SYNARA_POSTGRES_PASSWORD:?generated by scripts/synapse-integration.sh",
    "Compose must require a generated PostgreSQL password."
  );
  requireText(
    compose,
    "UID: ${SYNARA_UID:?generated by scripts/synapse-integration.sh}",
    "Synapse must use the host UID for private bind-mounted runtime state."
  );
  requireText(
    compose,
    "GID: ${SYNARA_GID:?generated by scripts/synapse-integration.sh}",
    "Synapse must use the host GID for private bind-mounted runtime state."
  );
  for (const placeholder of [
    "__POSTGRES_PASSWORD__",
    "__PUBLIC_PORT__",
    "__REGISTRATION_SECRET__",
    "__MACAROON_SECRET__",
    "__FORM_SECRET__",
  ]) {
    requireText(
      template,
      placeholder,
      `Missing runtime secret placeholder ${placeholder}.`
    );
  }
  requireText(
    launcher,
    "umask 077",
    "Harness secrets must be created with a private umask."
  );
  requireText(
    launcher,
    "openssl rand",
    "Harness secrets must be generated at runtime."
  );
  requireText(
    launcher,
    "down --volumes",
    "Harness must provide disposable-volume cleanup."
  );
  requireText(
    launcher,
    'find "$runtime_dir" -mindepth 1 -maxdepth 1 ! -name .gitkeep -exec rm -rf -- {} +',
    "Harness reset must remove all generated runtime children while preserving .gitkeep."
  );
  requireText(
    ignore,
    "runtime/*",
    "Generated harness runtime state must be ignored."
  );

  if (/registration_shared_secret:\s*["']?[a-f0-9]{16}/i.test(template)) {
    errors.push(
      "The committed homeserver template contains a registration secret."
    );
  }
  if (/POSTGRES_PASSWORD:\s*["']?[a-f0-9]{16}/i.test(compose)) {
    errors.push("The committed Compose file contains a PostgreSQL password.");
  }

  for (const command of ["status", "logs"]) {
    const commandCase = getCommandCase(launcher, command);
    if (!commandCase) {
      errors.push(`Harness launcher is missing the ${command} command.`);
      continue;
    }
    if (commandCase.includes("initialize_runtime")) {
      errors.push(
        `${command} must not initialize runtime secrets or configuration.`
      );
    }
    if (!commandCase.includes("require_initialized_runtime")) {
      errors.push(`${command} must require an already initialized runtime.`);
    }
  }

  const resetCase = getCommandCase(launcher, "reset");
  if (!resetCase?.includes("clear_runtime")) {
    errors.push("Harness reset must clear all generated runtime state.");
  }

  return { ok: errors.length === 0, errors };
}

function main() {
  const harness = path.join(root, "integration/synapse");
  const result = inspectSynapseHarness({
    compose: readFileSync(path.join(harness, "compose.yml"), "utf8"),
    template: readFileSync(
      path.join(harness, "homeserver.yaml.template"),
      "utf8"
    ),
    launcher: readFileSync(
      path.join(root, "scripts/synapse-integration.sh"),
      "utf8"
    ),
    ignore: readFileSync(path.join(harness, ".gitignore"), "utf8"),
  });

  for (const error of result.errors)
    console.error(`[synapse-harness] ${error}`);
  if (!result.ok) process.exit(1);
  console.log(
    "[synapse-harness] pinned images and generated-secret boundaries are valid."
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main();
}
